// Package pwa turns a WebAssembly build into an installable progressive
// web app: a web app manifest, icons, a service worker that caches the
// app for offline use, and the tags in index.html that tie them in.
package pwa

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"image"
	"image/png"
	"os"
	"path/filepath"
	"sort"
	"strings"

	_ "image/jpeg"

	"golang.org/x/image/draw"
)

// App describes the web app.
type App struct {
	Name, ShortName, Description string
	// ID is the app's ID, used as the manifest's id.
	ID string
	// Icon is a square PNG or JPEG (optional).
	Icon string
	// ThemeColor and BackgroundColor are CSS colors; Display is
	// standalone by default.
	ThemeColor, BackgroundColor, Display string
}

// Make adds the PWA files to the site in dir and links them from
// index.html.
func Make(a App, dir string) error {
	if a.Display == "" {
		a.Display = "standalone"
	}
	if a.ThemeColor == "" {
		a.ThemeColor = "#000000"
	}
	if a.BackgroundColor == "" {
		a.BackgroundColor = a.ThemeColor
	}
	if a.ShortName == "" {
		a.ShortName = a.Name
	}
	type icon struct {
		Src     string `json:"src"`
		Sizes   string `json:"sizes"`
		Type    string `json:"type"`
		Purpose string `json:"purpose,omitempty"`
	}
	var icons []icon
	if a.Icon != "" {
		for _, s := range []int{192, 512} {
			if err := writeIcon(a.Icon, filepath.Join(dir, fmt.Sprintf("icon-%d.png", s)), s, 0); err != nil {
				return fmt.Errorf("icon: %w", err)
			}
			icons = append(icons, icon{Src: fmt.Sprintf("icon-%d.png", s), Sizes: fmt.Sprintf("%dx%d", s, s), Type: "image/png"})
		}
		// Maskable: the icon inside the 80% safe zone, on the
		// background color, so launchers can crop it to any shape.
		if err := writeIcon(a.Icon, filepath.Join(dir, "icon-maskable-512.png"), 512, 0.1); err != nil {
			return err
		}
		icons = append(icons, icon{Src: "icon-maskable-512.png", Sizes: "512x512", Type: "image/png", Purpose: "maskable"})
		if err := writeIcon(a.Icon, filepath.Join(dir, "apple-touch-icon.png"), 180, 0); err != nil {
			return err
		}
	}
	manifest, err := json.MarshalIndent(map[string]any{
		"id":               "./?app=" + a.ID,
		"name":             a.Name,
		"short_name":       a.ShortName,
		"description":      a.Description,
		"start_url":        "./",
		"scope":            "./",
		"display":          a.Display,
		"theme_color":      a.ThemeColor,
		"background_color": a.BackgroundColor,
		"icons":            icons,
	}, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "manifest.webmanifest"), manifest, 0o644); err != nil {
		return err
	}
	if err := writeServiceWorker(dir); err != nil {
		return err
	}
	return patchIndex(filepath.Join(dir, "index.html"), a, len(icons) > 0)
}

// writeServiceWorker writes sw.js caching every file of the site, under
// a cache named after their content: a new build gets a new cache, and
// the old one is dropped once it takes over.
func writeServiceWorker(dir string) error {
	var files []string
	h := sha256.New()
	err := filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(dir, p)
		rel = filepath.ToSlash(rel)
		if rel == "sw.js" {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		h.Write([]byte(rel))
		h.Write(b)
		files = append(files, rel)
		return nil
	})
	if err != nil {
		return err
	}
	sort.Strings(files)
	list, _ := json.Marshal(append([]string{"./"}, files...))
	version := hex.EncodeToString(h.Sum(nil))[:12]
	sw := `// Generated by giode: caches the app for offline use.
const CACHE = "giode-` + version + `";
const FILES = ` + string(list) + `;

self.addEventListener("install", (e) => {
	e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
	e.waitUntil(caches.keys()
		.then((keys) => Promise.all(keys.filter((k) => k.startsWith("giode-") && k !== CACHE).map((k) => caches.delete(k))))
		.then(() => self.clients.claim()));
});

// The app's own files come from the cache; anything else (an API) from
// the network.
self.addEventListener("fetch", (e) => {
	if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) {
		return;
	}
	e.respondWith(caches.match(e.request, {ignoreSearch: true}).then((r) => r || fetch(e.request)));
});
`
	return os.WriteFile(filepath.Join(dir, "sw.js"), []byte(sw), 0o644)
}

// patchIndex adds the manifest, theme color, touch icon and service
// worker registration to index.html.
func patchIndex(path string, a App, icons bool) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	s := string(b)
	if strings.Contains(s, `rel="manifest"`) {
		return nil
	}
	head := "\t\t<link rel=\"manifest\" href=\"manifest.webmanifest\">\n" +
		"\t\t<meta name=\"theme-color\" content=\"" + a.ThemeColor + "\">\n" +
		"\t\t<meta name=\"apple-mobile-web-app-capable\" content=\"yes\">\n"
	if icons {
		head += "\t\t<link rel=\"apple-touch-icon\" href=\"apple-touch-icon.png\">\n"
	}
	head += "\t\t<script>if (\"serviceWorker\" in navigator) { addEventListener(\"load\", () => navigator.serviceWorker.register(\"sw.js\")); }</script>\n"
	i := strings.Index(s, "</head>")
	if i < 0 {
		return fmt.Errorf("%s has no </head>", path)
	}
	s = s[:i] + head + "\t" + s[i:]
	return os.WriteFile(path, []byte(s), 0o644)
}

// writeIcon renders the icon at size, inset by pad (a fraction of the
// size) on each side.
func writeIcon(src, dst string, size int, pad float64) error {
	f, err := os.Open(src)
	if err != nil {
		return err
	}
	defer f.Close()
	img, _, err := image.Decode(f)
	if err != nil {
		return err
	}
	out := image.NewNRGBA(image.Rect(0, 0, size, size))
	inset := int(float64(size) * pad)
	if inset > 0 {
		// The corner pixel's color stands in for the background.
		c := img.At(img.Bounds().Min.X, img.Bounds().Min.Y)
		draw.Draw(out, out.Bounds(), image.NewUniform(c), image.Point{}, draw.Src)
	}
	draw.CatmullRom.Scale(out, image.Rect(inset, inset, size-inset, size-inset), img, img.Bounds(), draw.Over, nil)
	var b bytes.Buffer
	if err := png.Encode(&b, out); err != nil {
		return err
	}
	return os.WriteFile(dst, b.Bytes(), 0o644)
}
